// ---------------------------------------------------------------- PDF writer
const esc = (t) => t.replace(/[()\\]/g, (c) => '\\' + c);

/** Stroked circle as four Bézier arcs. */
function circle(cx, cy, r) {
  const k = 0.5523 * r;
  return `${cx + r} ${cy} m ${cx + r} ${cy + k} ${cx + k} ${cy + r} ${cx} ${cy + r} c `
    + `${cx - k} ${cy + r} ${cx - r} ${cy + k} ${cx - r} ${cy} c `
    + `${cx - r} ${cy - k} ${cx - k} ${cy - r} ${cx} ${cy - r} c `
    + `${cx + k} ${cy - r} ${cx + r} ${cy - k} ${cx + r} ${cy} c S\n`;
}

/** Centred line of bold text (Helvetica-Bold averages ~0.6 em per capital). */
function centred(text, cx, y, size) {
  const x = cx - (text.length * size * 0.6) / 2;
  return `BT /F2 ${size} Tf ${x.toFixed(1)} ${y} Td (${esc(text)}) Tj ET\n`;
}

/**
 * The auditor's sign-off drawn at the foot of a page: a round firm seal, an
 * ink-blue handwritten-style signature, and the signatory details. Audited
 * statements are rejected by verification without a seal and signature.
 */
function signOff(s) {
  let g = 'q\n0.13 0.2 0.62 RG 0.13 0.2 0.62 rg\n';
  // Seal: double ring with the firm's details inside.
  g += '2 w\n' + circle(120, 130, 58) + '1 w\n' + circle(120, 130, 50);
  g += centred('ABC & ASSOCIATES', 120, 150, 6.5);
  g += centred('CHARTERED', 120, 134, 9);
  g += centred('ACCOUNTANTS', 120, 122, 9);
  g += centred('FRN 123456W', 120, 104, 7);
  // Signature: flowing strokes in ink blue.
  g += '0.05 0.1 0.55 RG 1.6 w 1 J 1 j\n'
    + '330 150 m 340 185 352 118 366 160 c 374 186 384 128 398 152 c 410 172 418 132 432 150 c '
    + '444 166 456 140 470 156 c 480 168 492 150 512 158 c S\n'
    + '1.1 w 338 136 m 380 128 440 132 508 140 c S\n';
  g += 'Q\n';
  // Signatory details under the signature.
  const lines = [
    'CA A. B. Example, Partner (M.No. 112233)',
    'For ABC & Associates, Chartered Accountants',
    'FRN 123456W   UDIN: 25112233BKABCD1234',
    `Place: ${STATE}   Date: 30/09/${s.fy.slice(0, 2)}${s.fy.slice(-2)}`,
  ];
  g += 'BT /F1 8 Tf 300 112 Td 11 TL\n' + lines.map((l) => `(${esc(l)}) Tj T*`).join('\n') + '\nET\n';
  return g;
}

function pdf(pages, { mark, signed, section }) {
  const objs = [];
  objs[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objs[2] = `<< /Type /Pages /Kids [${pages.map((_, i) => `${3 + i * 2} 0 R`).join(' ')}] /Count ${pages.length} >>`;
  const fontId = 3 + pages.length * 2;
  pages.forEach((lines, i) => {
    const pid = 3 + i * 2;
    const all = mark ? [...lines, '', MARK] : lines;
    let s = 'BT /F1 9 Tf 40 800 Td 13 TL\n' + all.map((l) => `(${esc(l)}) Tj T*`).join('\n') + '\nET\n';
    if (signed && i === pages.length - 1) s += signOff(section);
    objs[pid] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 ${fontId} 0 R /F2 ${fontId + 1} 0 R >> >> /Contents ${pid + 1} 0 R >>`;
    objs[pid + 1] = `<< /Length ${Buffer.byteLength(s)} >>\nstream\n${s}\nendstream`;
  });
  objs[fontId] = '<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>';
  objs[fontId + 1] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>';
  let out = '%PDF-1.4\n';
  const offs = [];
  for (let i = 1; i < objs.length; i++) {
    offs[i] = Buffer.byteLength(out);
    out += `${i} 0 obj\n${objs[i]}\nendobj\n`;
  }
  const xref = Buffer.byteLength(out);
  out += `xref\n0 ${objs.length}\n0000000000 65535 f \n` + offs.slice(1).map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objs.length} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return out;
}

for (const [section, s] of Object.entries(SECTIONS)) {
  const dir = path.join(__dirname, section);
  fs.mkdirSync(dir, { recursive: true });
  for (const [docId, build] of Object.entries(DOCS)) {
    if (section === 'provisional' && docId === 'auditors-report') continue; // no auditor's report for provisional
    // Audited statements carry the auditor's seal + signature and no dummy
    // banner (verification rejects both an unsigned statement and a file that
    // calls itself a dummy). Provisional statements stay marked as dummies.
    const audited = section === 'audited';
    fs.writeFileSync(path.join(dir, `${docId}.pdf`), pdf(build(s), { mark: !audited, signed: audited, section: s }));
  }
  console.log(`${section}: ${fs.readdirSync(dir).join(', ')}`);
}
